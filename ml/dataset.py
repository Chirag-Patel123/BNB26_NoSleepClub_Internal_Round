"""Dataset loader and step-level tabular feature matrix builder for P2.

Reads synthetic execution traces (JSONL) generated by P1.
Extracts step-level feature vectors with zero label leakage.
Splits by whole run/scenario:
  - train (70% of known scenarios)
  - validation (15% of known scenarios)
  - test (15% of known scenarios + 100% of held-out scenario 'flight_tight_budget')
"""
from __future__ import annotations
import json
import pathlib
from typing import Any, Dict, List, Optional, Tuple
import pandas as pd
import numpy as np

from .features import FEATURE_NAMES, extract_run_features

DEFAULT_DATASET_PATH = pathlib.Path("data/synthetic/runs.jsonl")
DEFAULT_BENCHMARK_PATH = pathlib.Path("data/synthetic/benchmark_cases.json")


def load_runs_from_jsonl(path: str | pathlib.Path = DEFAULT_DATASET_PATH) -> List[Dict[str, Any]]:
    """Loads all run dictionaries from a JSONL file."""
    p = pathlib.Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Runs dataset not found at {p}")
    runs: List[Dict[str, Any]] = []
    with open(p, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                runs.append(json.loads(line))
    return runs


def build_step_dataset(
    runs: List[Dict[str, Any]],
) -> Tuple[pd.DataFrame, pd.Series, pd.DataFrame]:
    """Converts a list of runs into tabular step-level features (X), labels (y), and metadata.

    Zero-leakage guarantee:
      `ground_truth` is only used to compute the binary label `y`.
      `X` contains ONLY features observable from step execution facts.

    Returns:
      X: pd.DataFrame of numeric features with columns == FEATURE_NAMES
      y: pd.Series of binary targets (1 if step == target_step_id, else 0)
      meta: pd.DataFrame with run_id, step_id, step_index, scenario_id, split, failure_type, task
    """
    rows_X: List[Dict[str, float]] = []
    labels: List[int] = []
    meta_rows: List[Dict[str, Any]] = []

    for r in runs:
        run_obj = r.get("run") or {}
        gt = r.get("ground_truth") or {}
        run_id = run_obj.get("run_id", "")
        scenario_id = run_obj.get("scenario_id", "")
        task = run_obj.get("task", "")
        split = r.get("split", "train")
        failure_type = gt.get("failure_type", "none")
        target_step_id = gt.get("target_step_id")

        feature_list, evidence_list, step_ids = extract_run_features(r)

        for f_dict, evs, s_id in zip(feature_list, evidence_list, step_ids):
            # Binary classification label: 1 if this step caused the failure
            is_root_cause = 1 if (target_step_id and s_id == target_step_id) else 0

            rows_X.append(f_dict)
            labels.append(is_root_cause)
            meta_rows.append({
                "run_id": run_id,
                "step_id": s_id,
                "step_index": int(f_dict.get("step_index", 0)),
                "scenario_id": scenario_id,
                "split": split,
                "failure_type": failure_type,
                "target_step_id": target_step_id,
                "task": task,
                "evidence": evs,
            })

    X = pd.DataFrame(rows_X, columns=FEATURE_NAMES).fillna(0.0)
    y = pd.Series(labels, name="is_failure_origin", dtype=np.int32)
    meta = pd.DataFrame(meta_rows)

    return X, y, meta


def load_dataset_splits(
    path: str | pathlib.Path = DEFAULT_DATASET_PATH,
) -> Dict[str, Dict[str, Any]]:
    """Loads dataset and splits it cleanly by run into train, validation, and test sets.

    Returns dict with keys: 'train', 'validation', 'test', 'held_out_test'.
    Each split contains:
      - 'X': pd.DataFrame
      - 'y': pd.Series
      - 'meta': pd.DataFrame
    """
    runs = load_runs_from_jsonl(path)
    X, y, meta = build_step_dataset(runs)

    splits: Dict[str, Dict[str, Any]] = {}
    for split_name in ("train", "validation", "test"):
        mask = (meta["split"] == split_name).values
        splits[split_name] = {
            "X": X.loc[mask].reset_index(drop=True),
            "y": y.loc[mask].reset_index(drop=True),
            "meta": meta.loc[mask].reset_index(drop=True),
        }

    # Held out scenario subset (flight_tight_budget in test)
    held_out_mask = (meta["scenario_id"] == "flight_tight_budget").values
    splits["held_out_test"] = {
        "X": X.loc[held_out_mask].reset_index(drop=True),
        "y": y.loc[held_out_mask].reset_index(drop=True),
        "meta": meta.loc[held_out_mask].reset_index(drop=True),
    }

    return splits
